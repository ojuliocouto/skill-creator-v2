#!/usr/bin/env python3
"""Analyze all skills in ~/.claude/skills/ and extract patterns."""

import sys
import json
import re
import os
from pathlib import Path
from collections import Counter

SKILLS_DIR = Path.home() / ".claude" / "skills"
SELF_NAME = "skill-creator-v2"

# Import sibling module
sys.path.insert(0, str(Path(__file__).parent))
from extract_frontmatter import extract_frontmatter, extract_body

# Windows consoles default to cp1252; force UTF-8 so accents and symbols never crash output.
for _stream in (sys.stdout, sys.stderr):
    if hasattr(_stream, "reconfigure"):
        _stream.reconfigure(encoding="utf-8", errors="replace")



def scan_all_skills() -> list:
    """Scan all SKILL.md files and extract metadata."""
    skills = []
    for skill_dir in sorted(SKILLS_DIR.iterdir()):
        if not skill_dir.is_dir() or skill_dir.name == SELF_NAME:
            continue
        skill_md = skill_dir / "SKILL.md"
        if not skill_md.exists():
            continue
        fm = extract_frontmatter(str(skill_md))
        body = extract_body(str(skill_md))

        # Detect structure
        has_scripts = (skill_dir / "scripts").is_dir()
        has_references = (skill_dir / "references").is_dir()
        has_config = (skill_dir / "config.json").exists()
        has_assets = (skill_dir / "assets").is_dir()

        scripts = []
        if has_scripts:
            scripts = [f.name for f in (skill_dir / "scripts").iterdir() if f.is_file()]

        references = []
        if has_references:
            for f in (skill_dir / "references").rglob("*"):
                if f.is_file():
                    references.append(str(f.relative_to(skill_dir / "references")))

        # Detect category
        category = detect_category(fm, body, scripts)

        # Extract sections from body
        sections = re.findall(r"^##?\s+(.+)$", body, re.MULTILINE)

        skills.append({
            "name": fm.get("name", skill_dir.name),
            "dir": skill_dir.name,
            "description_length": len(fm.get("description", "")),
            "body_length": len(body),
            "body_lines": body.count("\n"),
            "has_frontmatter": bool(fm),
            "has_triggers": bool(fm.get("triggers")),
            "has_pairs_with": bool(fm.get("pairs-with") or fm.get("pairs_with")),
            "has_allowed_tools": bool(fm.get("allowed-tools") or fm.get("allowed_tools")),
            "has_scripts": has_scripts,
            "has_references": has_references,
            "has_config": has_config,
            "has_assets": has_assets,
            "scripts": scripts,
            "references": references,
            "category": category,
            "sections": sections[:10],
            "triggers": fm.get("triggers", []),
        })

    return skills


def detect_category(fm: dict, body: str, scripts: list) -> str:
    """Heuristic category detection."""
    desc = (fm.get("description", "") + " " + fm.get("name", "")).lower()
    body_lower = body.lower()

    api_signals = ["api", "webhook", "endpoint", "token", "curl", "rest", "oauth"]
    workflow_signals = ["workflow", "pipeline", "etapa", "step", "fase", "protocolo"]
    analysis_signals = ["analis", "benchmark", "metric", "funnel", "dashboard", "report"]
    creative_signals = ["criativ", "gera", "imagem", "video", "audio", "visual", "design"]
    utility_signals = ["ffmpeg", "scrap", "transcri", "convert", "extract", "util"]

    scores = {
        "api-integration": sum(1 for s in api_signals if s in desc or s in body_lower[:500]),
        "workflow": sum(1 for s in workflow_signals if s in desc or s in body_lower[:500]),
        "analysis": sum(1 for s in analysis_signals if s in desc or s in body_lower[:500]),
        "creative": sum(1 for s in creative_signals if s in desc or s in body_lower[:500]),
        "utility": sum(1 for s in utility_signals if s in desc or s in body_lower[:500]),
    }

    if max(scores.values()) == 0:
        return "workflow"  # default
    return max(scores, key=scores.get)


def search_skills(query: str, skills: list) -> list:
    """Search skills by name, description keywords, or triggers."""
    query_lower = query.lower()
    results = []
    for s in skills:
        score = 0
        # Name match
        if query_lower in s["name"].lower():
            score += 10
        # Trigger match
        for t in s.get("triggers", []):
            if isinstance(t, str) and query_lower in t.lower():
                score += 5
        # Category match
        if query_lower in s.get("category", ""):
            score += 3
        if score > 0:
            results.append({**s, "_search_score": score})

    return sorted(results, key=lambda x: x["_search_score"], reverse=True)


def generate_patterns_report(skills: list) -> str:
    """Generate patterns.md content from analyzed skills."""
    lines = [
        "# Patterns Extracted from Existing Skills",
        f"\n> Auto-generated by analyze_skills.py: {len(skills)} skills analyzed",
        ""
    ]

    # Category distribution
    cats = Counter(s["category"] for s in skills)
    lines.append("## Category Distribution")
    for cat, count in cats.most_common():
        lines.append(f"- **{cat}**: {count} skills")
    lines.append("")

    # Structure patterns
    lines.append("## Structure Patterns")
    with_fm = sum(1 for s in skills if s["has_frontmatter"])
    with_triggers = sum(1 for s in skills if s["has_triggers"])
    with_scripts = sum(1 for s in skills if s["has_scripts"])
    with_refs = sum(1 for s in skills if s["has_references"])
    with_config = sum(1 for s in skills if s["has_config"])
    with_pairs = sum(1 for s in skills if s["has_pairs_with"])
    with_tools = sum(1 for s in skills if s["has_allowed_tools"])

    lines.append(f"- Frontmatter: {with_fm}/{len(skills)} ({100*with_fm//len(skills)}%)")
    lines.append(f"- Triggers in frontmatter: {with_triggers}/{len(skills)}")
    lines.append(f"- allowed-tools: {with_tools}/{len(skills)}")
    lines.append(f"- pairs-with: {with_pairs}/{len(skills)}")
    lines.append(f"- scripts/ dir: {with_scripts}/{len(skills)}")
    lines.append(f"- references/ dir: {with_refs}/{len(skills)}")
    lines.append(f"- config.json: {with_config}/{len(skills)}")
    lines.append("")

    # Description length stats
    desc_lens = [s["description_length"] for s in skills if s["description_length"] > 0]
    if desc_lens:
        lines.append("## Description Length")
        lines.append(f"- Min: {min(desc_lens)} chars")
        lines.append(f"- Max: {max(desc_lens)} chars")
        lines.append(f"- Median: {sorted(desc_lens)[len(desc_lens)//2]} chars")
        lines.append(f"- Mean: {sum(desc_lens)//len(desc_lens)} chars")
        lines.append("")

    # Body size stats
    body_lines = [s["body_lines"] for s in skills]
    lines.append("## Body Size (lines)")
    lines.append(f"- Min: {min(body_lines)}")
    lines.append(f"- Max: {max(body_lines)}")
    lines.append(f"- Median: {sorted(body_lines)[len(body_lines)//2]}")
    lines.append("")

    # Common section names
    all_sections = []
    for s in skills:
        all_sections.extend(s["sections"])
    section_counts = Counter(s.lower().strip() for s in all_sections)
    lines.append("## Most Common Section Names")
    for name, count in section_counts.most_common(15):
        lines.append(f"- \"{name}\": {count} skills")
    lines.append("")

    # Scripts patterns
    all_scripts = []
    for s in skills:
        all_scripts.extend(s["scripts"])
    if all_scripts:
        script_counts = Counter(all_scripts)
        lines.append("## Common Script Names")
        for name, count in script_counts.most_common(10):
            lines.append(f"- `{name}`: {count}")
        lines.append("")

    # Top skills by complexity
    lines.append("## Top 10 Most Complex Skills (by body size)")
    for s in sorted(skills, key=lambda x: x["body_lines"], reverse=True)[:10]:
        lines.append(f"- **{s['name']}**: {s['body_lines']} lines, {len(s['scripts'])} scripts, {len(s['references'])} refs")
    lines.append("")

    # Skills catalog
    lines.append("## Full Catalog")
    for s in sorted(skills, key=lambda x: x["name"]):
        flags = []
        if s["has_scripts"]: flags.append("scripts")
        if s["has_references"]: flags.append("refs")
        if s["has_config"]: flags.append("config")
        lines.append(f"- **{s['name']}** [{s['category']}]: {s['body_lines']}L {', '.join(flags)}")

    return "\n".join(lines)


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description="Analyze existing skills")
    parser.add_argument("--search", help="Search for skills matching query")
    parser.add_argument("--generate-patterns", action="store_true", help="Generate patterns.md")
    parser.add_argument("--json", action="store_true", help="Output as JSON")
    parser.add_argument("--summary", action="store_true", help="Print summary stats")
    args = parser.parse_args()

    skills = scan_all_skills()

    if args.search:
        results = search_skills(args.search, skills)
        if args.json:
            print(json.dumps(results, indent=2, ensure_ascii=False))
        else:
            if not results:
                print(f"No skills found matching '{args.search}'")
            for r in results:
                print(f"[score={r['_search_score']}] {r['name']} ({r['category']}): {r['dir']}/")
                if r.get("triggers"):
                    triggers = r["triggers"][:5]
                    print(f"  triggers: {', '.join(str(t) for t in triggers)}")
        sys.exit(0)

    if args.generate_patterns:
        report = generate_patterns_report(skills)
        # Write to references/patterns.md
        output = Path(__file__).parent.parent / "references" / "patterns.md"
        output.write_text(report, encoding="utf-8")
        print(f"Generated {output} ({len(report)} chars, {len(skills)} skills)")
        sys.exit(0)

    if args.summary:
        cats = Counter(s["category"] for s in skills)
        print(f"Total skills: {len(skills)}")
        for cat, count in cats.most_common():
            print(f"  {cat}: {count}")
        print(f"With scripts: {sum(1 for s in skills if s['has_scripts'])}")
        print(f"With references: {sum(1 for s in skills if s['has_references'])}")
        print(f"With config: {sum(1 for s in skills if s['has_config'])}")
        sys.exit(0)

    # Default: JSON dump
    print(json.dumps(skills, indent=2, ensure_ascii=False))
